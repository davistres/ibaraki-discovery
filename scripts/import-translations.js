  console.log('Starting import of translations...');

  // Update Places
  const updatePlaceStmt = db.prepare(`
    UPDATE Place SET
      nom_en = ?, nom_ja = ?,
      description_en = COALESCE(?, description_en), description_ja = COALESCE(?, description_ja),
      descriptionLongue_en = ?, descriptionLongue_ja = ?,
      adresse_ja = ?, acces_en = ?, acces_ja = ?,
      horaires_en = ?, horaires_ja = ?,
      tarif_en = ?, tarif_ja = ?,
      dureeVisite_en = ?, dureeVisite_ja = ?
    WHERE id = ?
  `);

  places.forEach(p => {
    updatePlaceStmt.run(
      p.nom_en || '', p.nom_ja || '',
      p.description_en || null, p.description_ja || null,
      p.descriptionLongue_en || '', p.descriptionLongue_ja || '',
      p.adresse_ja || '', p.acces_en || '', p.acces_ja || '',
      p.horaires_en || '', p.horaires_ja || '',
      p.tarif_en || '', p.tarif_ja || '',
      p.dureeVisite_en || '', p.dureeVisite_ja || '',
      p.id
    );
  });
  updatePlaceStmt.finalize();
  console.log(`Updated ${places.length} places.`);

  // Update Festivals
  const updateFestivalStmt = db.prepare(`
    UPDATE Festival SET
      lieu_en = ?, lieu_ja = ?,
      periode_en = ?, periode_ja = ?
    WHERE id = ?
  `);

  festivals.forEach(f => {
    updateFestivalStmt.run(
      f.lieu_en || '', f.lieu_ja || '',
      f.periode_en || '', f.periode_ja || '',
      f.id
    );
  });
  updateFestivalStmt.finalize();
  console.log(`Updated ${festivals.length} festivals.`);

  // Update Categories
  const updateCategoryStmt = db.prepare(`
    UPDATE Category SET
      nom_en = ?, nom_ja = ?
    WHERE id = ?
  `);

  categories.forEach(c => {
    updateCategoryStmt.run(c.nom_en, c.nom_ja, c.id);
  });
  updateCategoryStmt.finalize();
